/// The characters of a property, by what stands between the braces of `\p{…}`: a name and a
/// value around a `=`, or the one of the two that stands alone.
///
/// # Errors
///
/// When ECMA-262 has no such property or value, and when `regex-syntax` has no characters
/// for one that it has.
pub(super) fn characters(name: Option<&str>, value: &str) -> Result<ClassUnicode, Refusal> {
    let listed = |names: &[&str]| names.binary_search(&value).is_ok();
    let query = match name {
        Some("General_Category" | "gc") if listed(&GENERAL_CATEGORIES) => format!("gc={value}"),
        Some("Script" | "sc") if listed(&SCRIPTS) => format!("sc={value}"),
        Some("Script_Extensions" | "scx") if listed(&SCRIPTS) => format!("scx={value}"),
        // A value that stands alone is one of `General_Category`.
        None if listed(&GENERAL_CATEGORIES) => format!("gc={value}"),
        None if listed(&BINARY) => value.to_owned(),
        _ => return Err(Refusal::Invalid),
    };
    // No string of a JSON document holds a surrogate.
    if matches!(query.as_str(), "gc=Cs" | "gc=Surrogate") {
        return Ok(ClassUnicode::empty());
    }
    let read = regex_syntax::Parser::new().parse(&format!(r"\p{{{query}}}"));
    match read.as_ref().map(regex_syntax::hir::Hir::kind) {
        Ok(HirKind::Class(Class::Unicode(characters))) => Ok(characters.clone()),
        // A set of one character comes back as that character.
        Ok(HirKind::Literal(literal)) => {
            let character = std::str::from_utf8(&literal.0).ok();
            let character = character.and_then(|text| text.chars().next());
            let character = character.ok_or(Refusal::NotModelled)?;
            Ok(ClassUnicode::new([ClassUnicodeRange::new(
                character, character,
            )]))
        }
        _ => Err(Refusal::NotModelled),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tables_are_sorted_so_that_a_name_is_found() {
        for names in [&GENERAL_CATEGORIES[..], &SCRIPTS[..], &BINARY[..]] {
            assert!(names.is_sorted());
            assert!(names.windows(2).all(|pair| pair[0] != pair[1]));
        }
    }

    #[test]
    fn regex_syntax_has_the_characters_of_all_names_but_a_few() {
        let mut without = Vec::new();
        for value in GENERAL_CATEGORIES {
            assert!(characters(None, value).is_ok(), "{value}");
            assert_eq!(
                characters(Some("gc"), value),
                characters(Some("General_Category"), value)
            );
        }
        for value in BINARY {
            if characters(None, value).is_err() {
                without.push(value.to_owned());
            }
        }
        for value in SCRIPTS {
            let found = ["Script", "sc", "Script_Extensions", "scx"]
                .map(|name| characters(Some(name), value));
            assert!(found.iter().all(|other| other.is_ok() == found[0].is_ok()));
            if found[0].is_err() {
                without.push(format!("Script={value}"));
            }
        }
        // Such a name is one of ECMA-262 all the same, and a pattern with it is not modelled:
        // one property, the scripts of a newer Unicode, and the scripts that are none.
        assert_eq!(characters(None, "CWKCF"), Err(Refusal::NotModelled));
        assert_eq!(characters(Some("sc"), "Zzzz"), Err(Refusal::NotModelled));
        assert!(without.len() <= 14, "{without:?}");
    }

    #[test]
    fn a_name_is_taken_as_the_standard_writes_it_and_no_other_way() {
        assert!(characters(None, "L").is_ok());
        assert!(characters(None, "Letter").is_ok());
        assert!(characters(Some("Script"), "Greek").is_ok());
        assert!(characters(Some("scx"), "Grek").is_ok());
        for (name, value) in [
            (None, "letter"),
            (None, "Greek"),
            (None, "Script"),
            (Some("Script"), "greek"),
            (Some("script"), "Greek"),
            (Some("gc"), "Greek"),
            (Some("sc"), "L"),
            (Some("Alphabetic"), "L"),
            (Some("gc"), "Alphabetic"),
            (None, ""),
        ] {
            assert_eq!(
                characters(name, value),
                Err(Refusal::Invalid),
                "{name:?} {value}"
            );
        }
    }

    #[test]
    fn a_set_of_one_character_and_one_of_none_are_sets() {
        let line = characters(None, "Zl").unwrap();
        assert_eq!(
            line.ranges(),
            [ClassUnicodeRange::new('\u{2028}', '\u{2028}')]
        );
        assert!(characters(None, "Cs").unwrap().ranges().is_empty());
        assert!(
            characters(Some("gc"), "Surrogate")
                .unwrap()
                .ranges()
                .is_empty()
        );
    }
}
